-- Student Result Management System
-- Database: Supabase PostgreSQL

create table if not exists public.admins (
  id bigint generated by default as identity primary key,
  username varchar(100) not null unique,
  password text not null
);

create table if not exists public.students (
  id bigint generated by default as identity primary key,
  name varchar(150) not null,
  roll_number varchar(50) not null unique,
  email varchar(150) not null unique,
  course varchar(100) not null,
  semester integer not null check (semester between 1 and 12),
  password text not null
);

create table if not exists public.results (
  id bigint generated by default as identity primary key,
  student_id bigint not null unique references public.students(id) on delete cascade,
  php numeric(5,2) not null check (php between 0 and 100),
  dbms numeric(5,2) not null check (dbms between 0 and 100),
  computer_network numeric(5,2) not null check (computer_network between 0 and 100),
  operating_system numeric(5,2) not null check (operating_system between 0 and 100),
  computer_graphics numeric(5,2) not null check (computer_graphics between 0 and 100),
  total numeric(7,2) not null,
  percentage numeric(5,2) not null,
  grade varchar(3) not null,
  status varchar(10) not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

