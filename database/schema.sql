-- Student Result Management System
-- Supabase PostgreSQL schema

create table if not exists admins (
    id bigint generated by default as identity primary key,
    username varchar(50) unique not null,
    password varchar(255) not null,
    created_at timestamptz not null default now()
);

create table if not exists students (
    id bigint generated by default as identity primary key,
    name varchar(100) not null,
    roll_number varchar(30) unique not null,
    email varchar(120),
    course varchar(80) not null default 'BCA',
    semester integer not null default 4 check (semester between 1 and 8),
    password varchar(255) not null,
    created_at timestamptz not null default now()
);

create table if not exists results (
    id bigint generated by default as identity primary key,
    student_id bigint not null references students(id) on delete cascade,
    php integer not null check (php between 0 and 100),
    dbms integer not null check (dbms between 0 and 100),
    computer_network integer not null check (computer_network between 0 and 100),
    operating_system integer not null check (operating_system between 0 and 100),
    computer_graphics integer not null check (computer_graphics between 0 and 100),
    total integer not null,
    percentage numeric(5,2) not null,
    grade varchar(2) not null,
    status varchar(10) not null check (status in ('PASS', 'FAIL')),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique(student_id)
);

create index if not exists idx_students_roll_number on students(roll_number);
create index if not exists idx_results_student_id on results(student_id);

